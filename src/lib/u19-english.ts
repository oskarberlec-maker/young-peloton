const JUNIOR_CLASSIFICATIONS = /^Objavljene dejanske razvrstitve; izrecnih individualnih Junior 17\/18: (\d+)$/;
const UCI_PLACINGS = /^Objavljenih (\d+) uvrstitev UCI; popolnost protokola ni dokazana$/;

export function englishCategory(value: string): string {
  const labels: Record<string,string> = {
    'M': 'Men', 'Ž': 'Women', 'M/Ž': 'Men & women', 'Ni potrjeno': 'Not confirmed',
  };
  return labels[value] ?? value;
}
export function englishRaceType(value: string): string {
  return TYPES[value] ?? value;
}
export function englishConfirmation(value: string): string {
  return CONFIRMATIONS[value] ?? value;
}
export function englishRaceNote(value: string): string {
  if (!value) return '';
  const explicitJunior = JUNIOR_CLASSIFICATIONS.exec(value);
  if (explicitJunior) return `Published actual classifications; explicitly listed individual juniors aged 17–18: ${explicitJunior[1]}`;
  const uci = UCI_PLACINGS.exec(value);
  if (uci) return `${uci[1]} UCI placings published; completeness of the results sheet not established`;
  return NOTES[value] ?? value;
}