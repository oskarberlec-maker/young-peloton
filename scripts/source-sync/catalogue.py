"""Read the existing generated TS race-source catalogue without executing JS.

The source list is generated by the app's archive and contains race-specific
officialUrl/otherUrls. Parsing is deliberately fail-closed: unmapped/ambiguous
URLs are never used to change race dates or categories.
"""
import gzip
import json
import re
from collections import defaultdict
from core import canonical
from urllib.parse import urlsplit, urlunsplit, parse_qs
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CATALOGUE = ROOT / "src/routes/-young-peloton-race-sources.ts"
EXCEL_SOURCES = ROOT / "scripts/source-sync/data/excel-result-sources-2026.json.gz"
STRING = r'"(?:\\.|[^"\\])*"|\x27(?:\\.|[^\x27\\])*\x27'
URL = re.compile(r'https?://[^\s\x27"<>\\]+', re.I)
ENTRY = re.compile(r'(["\x27])(?P<id>[^"\x27\n]{3,180})\1\s*:\s*\{(?P<body>[^{}]{0,100000})\}', re.S)


def _value(text):
    if text.startswith('"'):
        try:
            return json.loads(text)
        except json.JSONDecodeError:
            return text[1:-1]
    return text[1:-1].replace("\\'", "'").replace('\\/', '/')


def source_catalogue():
    if not CATALOGUE.exists():
        return {}
    text = CATALOGUE.read_text(encoding='utf-8')
    result = {}
    for m in ENTRY.finditer(text):
        race_id = m.group('id')
        if not re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9_.:–-]{2,179}', race_id):
            continue
        body = m.group('body')
        if not any(k in body for k in ('officialUrl', 'otherUrls')):
            continue
        # Extract all properly quoted HTTP links (not comments or code). The
        # monitor later canonicalizes them and applies trusted-identity checks.
        links = []
        for q in re.finditer(STRING, body):
            u = _value(q.group(0))
            if isinstance(u, str) and u.startswith(('https://', 'http://')) and u not in links:
                links.append(u)
        if links:
            result[race_id] = links
    return result


def excel_result_sources():
    """All 2026 result/evidence URLs from the 28,975-row workbook.

    File is keyed by original race ID, each value is a list of distinct URLs.
    URLs are retained by original ID even if that ID is no longer present in the
    website archive, so previously collected official source evidence is not lost.
    No external page may add an arbitrary race ID; only IDs from the supplied file.
    """
    if not EXCEL_SOURCES.exists():
        raise FileNotFoundError('Bundled Excel source archive is missing: ' + str(EXCEL_SOURCES))
    with gzip.open(EXCEL_SOURCES, 'rt', encoding='utf-8') as source:
        data = json.load(source)
    if not isinstance(data, dict) or len(data) < 9000:
        raise ValueError('Excel source archive is incomplete or corrupt')
    sources = {}
    for rid, urls in data.items():
        if not isinstance(rid, str) or not rid or len(rid) > 180 or not isinstance(urls, list):
            raise ValueError('Malformed race ID or URL list in Excel source archive')
        unique = set()
        for url in urls:
            if not isinstance(url, str):
                raise ValueError('Invalid Excel source URL')
            p = urlsplit(url)
            if p.scheme not in ('http', 'https') or not p.hostname or p.username or p.password:
                raise ValueError('Non-HTTP Excel source URL')
            # Mirror core.canonical: keep query string and meaningful path intact,
            # but discard irrelevant fragments before de-duplication.
            canonical_url = urlunsplit((p.scheme, p.netloc, p.path or '/', p.query, ''))
            unique.add(canonical_url)
        sources[rid] = sorted(unique)
    return sources


def combined_source_catalogue():
    """Keep all original sources and add the workbook links without duplicates."""
    original = source_catalogue()
    excel = excel_result_sources()
    merged = {rid: set(urls) for rid, urls in original.items()}
    for rid, urls in excel.items():
        merged.setdefault(rid, set()).update(urls)
    return {rid: sorted(urls) for rid, urls in sorted(merged.items())}


def official_event_key(url):
    """Only stable federation event IDs, never calendar paths or fuzzy names."""
    p = urlsplit(url)
    if p.hostname == 'www.federciclismo.it':
        rid = parse_qs(p.query).get('raceid', [''])[0]
        return ('IT', rid) if re.fullmatch(r'\d{1,20}', rid) else None
    if p.hostname == 'competitions.ffc.fr':
        match = re.search(r'/2026/([A-Za-z0-9-]{4,40})/', p.path)
        return ('FR', match[1]) if match else None
    if p.hostname == 'mijn.knwu.nl':
        match = re.fullmatch(r'/calendar/races/(\d+)/?', p.path)
        return ('NL', match[1]) if match else None
    return None


def linked_source_catalogue(races):
    """Resolve old xl-* source keys only with unique exact archive-URL evidence.

    The Excel result-source import already uses the actual race IDs and always
    takes precedence. An archive source URL shared by multiple races is *not*
    evidence for merging those races. Unresolved legacy sources stay monitored,
    but cannot change any race until a trustworthy identity is established.
    """
    by_id = {race['id']: race for race in races}
    anchors = defaultdict(set)
    stable = defaultdict(set)
    for race in races:
        if race['date'].startswith('2027-') or race.get('state') == 'merged' or race.get('duplicate'):
            continue
        try:
            if race.get('sourceUrl'):
                anchors[canonical(race['sourceUrl'])].add(race['id'])
                key = official_event_key(race['sourceUrl'])
                if key and key[0] == race.get('countryCode'):
                    stable[key].add(race['id'])
        except ValueError:
            pass

    merged = {rid: set(urls) for rid, urls in excel_result_sources().items()}
    metrics = {'legacyIdsMapped': 0, 'legacyIdsUnmapped': 0,
               'legacyLinksMapped': 0, 'legacyLinksUnmapped': 0,
               'legacyAmbiguousIds': 0}
    for old_id, urls in source_catalogue().items():
        # Retain the original association even when an additional verified mapping exists.
        merged.setdefault(old_id, set()).update(urls)
        actual_id = old_id if old_id in by_id else None
        if actual_id is None and old_id.startswith('xl-') and urls:
            try:
                candidates = anchors.get(canonical(urls[0]), set())
            except ValueError:
                candidates = set()
            key = official_event_key(urls[0])
            if not candidates and key:
                candidates = stable.get(key, set())
            if len(candidates) == 1:
                actual_id = next(iter(candidates))
            elif len(candidates) > 1:
                metrics['legacyAmbiguousIds'] += 1
        if actual_id:
            merged.setdefault(actual_id, set()).update(urls)
            metrics['legacyIdsMapped'] += 1
            metrics['legacyLinksMapped'] += len(urls)
        else:
            # Keep the URL under its historical identity for HTTP change
            # detection. Never use it to update an arbitrary current race.
            merged.setdefault(old_id, set()).update(urls)
            metrics['legacyIdsUnmapped'] += 1
            metrics['legacyLinksUnmapped'] += len(urls)

    return {rid: sorted(links) for rid, links in sorted(merged.items())}, metrics
